
#Ejercicio 3 : Pedir do numeros y mostrar Suma , Resta , Multiplicacion y Division 
#Inicializando numeros

num1 = int(input("Ingrese su primer numero: \n"))
num2 = int(input("Ingrese su segundo numero : \n"))

#Creando proccesos 

Suma = num1 + num2
Resta = num1 - num2
Multiplicacion = num1 * num2
Division = num1  / num2

print(f"===Resultados del ejercicio ===")
print(f"\n Suma : {Suma} \n Resta : {Resta} \n Multiplicacion : {Multiplicacion} \n Division : {Division}")