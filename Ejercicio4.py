
#Ejercicio 4 : Pide tres notas , Calcule , Muestre Resultados 

# Inicializando variables

nota1 = float(input("Escriba su primera nota : \n"))
nota2 = float(input("Escriba su segunda nota : \n"))
nota3 = float(input("Escriba su tecera nota : \n"))

#Calculando promedio
promedio = (nota1 + nota2 + nota3 ) / 3 

#Mostrando resultados
print(f"Su promedio es ... \n {promedio}")